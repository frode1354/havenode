def _state_py(plan: CrewPlan) -> str:
    fields = plan.state_fields or []
    lines = [
        '"""Global LangGraph WorkflowState — generated by Crew Studio."""',
        "from __future__ import annotations",
        "",
        "from typing import Any, TypedDict",
        "",
        "",
        "class WorkflowState(TypedDict, total=False):",
    ]
    if not fields:
        lines.append("    inputs: dict[str, Any]")
        lines.append("    messages: list[Any]")
        lines.append("    tokens_used: int")
        lines.append("    status: str")
        lines.append("    last_output: str")
    else:
        type_map = {
            "str": "str",
            "int": "int",
            "dict": "dict[str, Any]",
            "list": "list[Any]",
            "bool": "bool",
        }
        for f in fields:
            py_t = type_map.get(f.type, "Any")
            lines.append(f"    {f.name}: {py_t}  # {f.description or ''}".rstrip())
    lines.append("")
    lines.append("")
    lines.append("STATE_DEFAULTS: dict[str, Any] = {")
    for f in fields:
        if f.type == "int":
            val: Any = int(f.default) if str(f.default).isdigit() else 0
            lines.append(f'    "{f.name}": {val},')
        elif f.type == "dict":
            lines.append(f'    "{f.name}": {{}},')
        elif f.type == "list":
            lines.append(f'    "{f.name}": [],')
        else:
            d = (f.default or "").replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    "{f.name}": "{d}",')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _fix_graph_py(plan: CrewPlan) -> str:
    """Cleaner graph.py without the dict-key bug."""
    plan = ensure_workflow_plan(plan)
    crew_mods = [m for m in plan.modules if m.kind == "crew"]
    budget = (
        int(plan.run_policy.token_budget_max)
        if plan.run_policy and plan.run_policy.token_budget_max
        else "None"
    )
    mapping_lines = ",\n".join(
        f'        "{m.id}": "{(m.team_id or m.id).replace("-", "_")}"' for m in crew_mods
    )
    node_lines: list[str] = []
    for mod in plan.modules:
        if mod.kind == "end":
            continue
        if mod.kind == "crew":
            node_lines.append(f'    g.add_node("{mod.id}", make_crew_node("{mod.id}", budget))')
        elif mod.kind == "hitl":
            node_lines.append(f'    g.add_node("{mod.id}", hitl_node)')
        elif mod.kind == "router":
            node_lines.append(f'    g.add_node("{mod.id}", router_node)')
        else:
            node_lines.append(
                f'    g.add_node("{mod.id}", lambda s, _id="{mod.id}": {{**s, "last_output": _id}})'
            )
    edge_lines: list[str] = []
    for edge in plan.graph_edges:
        src = "START" if edge.source == "start" else f'"{edge.source}"'
        tgt_mod = next((m for m in plan.modules if m.id == edge.target), None)
        if edge.target in ("end", "mod_end") or (tgt_mod and tgt_mod.kind == "end"):
            tgt = "END"
        else:
            tgt = f'"{edge.target}"'
        if edge.condition:
            edge_lines.append(
                f"    # condition={edge.condition!r} label={edge.label!r}"
            )
        edge_lines.append(f"    g.add_edge({src}, {tgt})")

    return f'''"""LangGraph outer orchestration — generated by Crew Studio (portable)."""
from __future__ import annotations

import os
from typing import Any, Literal

from langgraph.graph import END, START, StateGraph

from state import STATE_DEFAULTS, WorkflowState

MODULE_PACKAGES = {{
{mapping_lines}
}}


def _tokens_of(text: str) -> int:
    return max(1, len(text or "") // 2)


def _run_crew_module(module_id: str, inputs: dict[str, Any]) -> str:
    """Kick off the CrewAI package for this module (crews/<pkg>)."""
    import importlib
    import sys
    from pathlib import Path

    pkg = MODULE_PACKAGES.get(module_id)
    if not pkg:
        return f"[skip] unknown module {{module_id}}"
    root = Path(__file__).resolve().parent / "crews" / pkg
    src = root / "src"
    if str(src) not in sys.path:
        sys.path.insert(0, str(src))
    mod = importlib.import_module(f"{{pkg}}.main")
    if hasattr(mod, "run"):
        # Optional: inject inputs via environment for templates that read os.environ
        for k, v in (inputs or {{}}).items():
            os.environ.setdefault(f"CREW_INPUT_{{k.upper()}}", str(v))
        return str(mod.run())
    return f"[ok] {{module_id}}"


def make_crew_node(module_id: str, budget: int | None):
    def node(state: WorkflowState) -> WorkflowState:
        inputs = dict(state.get("inputs") or {{}})
        output = _run_crew_module(module_id, inputs)
        used = int(state.get("tokens_used") or 0) + _tokens_of(output)
        status = str(state.get("status") or "running")
        if budget is not None and used > budget:
            status = "circuit_broken"
        messages = list(state.get("messages") or [])
        messages.append({{"module": module_id, "output": output[:2000]}})
        return {{
            **state,
            "last_output": output,
            "tokens_used": used,
            "status": status,
            "messages": messages,
        }}

    return node


def hitl_node(state: WorkflowState) -> WorkflowState:
    """Human-in-the-loop checkpoint (optional interrupt)."""
    try:
        from langgraph.types import interrupt

        if os.getenv("LANGGRAPH_HITL", "").strip().lower() in {{"1", "true", "yes"}}:
            feedback = interrupt(
                {{"prompt": "Human review required", "last_output": state.get("last_output")}}
            )
            return {{**state, "human_feedback": str(feedback), "branch": "approved"}}
    except Exception:
        pass
    return {{**state, "branch": "approved"}}


def router_node(state: WorkflowState) -> WorkflowState:
    fb = str(state.get("human_feedback") or state.get("last_output") or "").lower()
    branch: Literal["ok", "reject", "retry"]
    if "reject" in fb:
        branch = "reject"
    elif "retry" in fb:
        branch = "retry"
    else:
        branch = "ok"
    return {{**state, "branch": branch}}


def build_graph():
    budget = {budget}
    g = StateGraph(WorkflowState)
{chr(10).join(node_lines)}
{chr(10).join(edge_lines)}
    return g.compile()


def run(inputs: dict[str, Any] | None = None) -> WorkflowState:
    """Invoke the full workflow. Set LANGCHAIN_TRACING_V2=true for LangSmith."""
    app = build_graph()
    state: WorkflowState = {{
        **STATE_DEFAULTS,
        "inputs": dict(inputs or {{}}),
        "status": "running",
        "tokens_used": 0,
        "messages": [],
    }}
    return app.invoke(state)


if __name__ == "__main__":
    out = run()
    print(out.get("last_output") or out)
'''


def _readme(plan: CrewPlan) -> str:
    docs = generate_workflow_docs(plan)
    est = estimate_plan_tokens(plan)
    return f"""# {plan.title}

{plan.summary}

Portable **LangGraph + CrewAI** export from Crew Studio.  
No vendor lock-in — run locally without the Studio UI.

## Architecture

- **Outer**: LangGraph `StateGraph` (`graph.py`) — global State, edges, HITL, circuit breaker
- **Inner**: CrewAI Crew packages under `crews/<module>/` — Agents / Tasks

## Quick start

```bash
python -m venv .venv
# Windows: .\\.venv\\Scripts\\activate
source .venv/bin/activate
pip install -r requirements.txt
cp .env.example .env   # fill DEEPSEEK_API_KEY or OPENAI_API_KEY
python run.py
```

Or PowerShell: `./run_dev.ps1`

## Token budget

- Static ceiling (pre-run): **{est.total_max}** tokens
- Circuit breaker: `{plan.run_policy.token_budget_max if plan.run_policy else None}` (auto-stop when exceeded)

## Human-in-the-loop

```bash
set LANGGRAPH_HITL=true   # Windows
export LANGGRAPH_HITL=true
python run.py
```

## LangSmith tracing (optional)

```bash
export LANGCHAIN_TRACING_V2=true
export LANGCHAIN_API_KEY=...
```

## Docker

```bash
docker build -t {plan.name}-workflow .
docker run --env-file .env {plan.name}-workflow
```

## Workflow docs

See `WORKFLOW.md` (Mermaid + narrative).

## Sub-DAG replay

Each Crew under `crews/` can be run alone:

```bash
cd crews/<pkg>
uv sync   # or pip install -e .
uv run python -m <pkg>.main
```
"""


def _requirements() -> str:
    return "\n".join(
        [
            "langgraph>=0.2.0",
            "langchain-core>=0.3.0",
            "crewai[tools]>=1.15.0",
            "python-dotenv>=1.0.0",
            "pyyaml>=6.0",
            "",
        ]
    )


def _dockerfile(plan: CrewPlan) -> str:
    return f"""FROM python:3.12-slim
WORKDIR /app
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY . .
ENV PYTHONUNBUFFERED=1
CMD ["python", "run.py"]
"""


def _run_py() -> str:
    return '''#!/usr/bin/env python3
"""Entry point — load .env and invoke LangGraph workflow."""
from __future__ import annotations

import json
import os

from dotenv import load_dotenv

load_dotenv()

from graph import run  # noqa: E402


def main() -> None:
    raw = os.getenv("CREW_INPUTS_JSON", "{}")
    try:
        inputs = json.loads(raw) if raw else {}
    except json.JSONDecodeError:
        inputs = {}
    result = run(inputs if isinstance(inputs, dict) else {})
    print(result.get("last_output") or result)
    if result.get("status") == "circuit_broken":
        raise SystemExit(2)


if __name__ == "__main__":
    main()
'''


def _run_ps1() -> str:
    return """param(
  [string]$EnvFile = ".env"
)
$ErrorActionPreference = "Stop"
if (-not (Test-Path .venv)) { python -m venv .venv }
.\\.venv\\Scripts\\Activate.ps1
pip install -r requirements.txt
if (Test-Path $EnvFile) { Get-Content $EnvFile | ForEach-Object {
  if ($_ -match '^\\s*#' -or $_ -notmatch '=') { return }
  $k,$v = $_.Split('=',2); Set-Item -Path "Env:$k" -Value $v
}}
python run.py
"""


def langgraph_project_files(plan: CrewPlan, *, include_dockerfile: bool = True) -> dict[str, str]:
    plan = ensure_workflow_plan(plan)
    root = plan.name
    docs = generate_workflow_docs(plan)
    files: dict[str, str] = {
        f"{root}/README.md": _readme(plan),
        f"{root}/WORKFLOW.md": docs.markdown,
        f"{root}/requirements.txt": _requirements(),
        f"{root}/run.py": _run_py(),
        f"{root}/run_dev.ps1": _run_ps1(),
        f"{root}/state.py": _state_py(plan),
        f"{root}/graph.py": _fix_graph_py(plan),
        f"{root}/.env.example": (
            "DEEPSEEK_API_KEY=\n"
            "OPENAI_API_KEY=\n"
            "MODEL=deepseek/deepseek-chat\n"
            "LANGCHAIN_TRACING_V2=false\n"
            "LANGCHAIN_API_KEY=\n"
            "LANGGRAPH_HITL=false\n"
            "CREW_INPUTS_JSON={}\n"
        ),
        f"{root}/plan.json": json.dumps(plan.model_dump(mode="json"), ensure_ascii=False, indent=2),
    }
    if include_dockerfile:
        files[f"{root}/Dockerfile"] = _dockerfile(plan)

    # Embed each Crew module as its own AMP-compatible package
    for mod in plan.modules:
        if mod.kind != "crew":
            continue
        try:
            sliced = crew_slice_for_module(plan, mod.id)
        except ValueError:
            continue
        pkg_name = (mod.team_id or mod.id).replace("-", "_")
        sliced = sliced.model_copy(update={"name": pkg_name})
        for rel, content in project_files(sliced).items():
            # project_files keys look like "{pkg}/..."
            suffix = rel.split("/", 1)[-1] if "/" in rel else rel
            files[f"{root}/crews/{pkg_name}/{suffix}"] = content

    return files


def build_langgraph_zip(plan: CrewPlan, *, include_dockerfile: bool = True) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for rel, content in langgraph_project_files(
            plan, include_dockerfile=include_dockerfile
        ).items():
            zf.writestr(rel, content)
    return buf.getvalue()
